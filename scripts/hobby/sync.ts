#!/usr/bin/env ts-node

import type { HobbyItemMap } from '../../shared/types/hobby'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { collectBangumi } from './adapters/bangumi'
import { collectSteam } from './adapters/steam'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const outputPath = path.resolve(__dirname, '../../content/data/hobbies.generated.ts')
const dryRun = process.argv.includes('--dry-run')

// 独立脚本不经过 Nuxt，需要自行加载 .env
const loadEnvFile = (process as typeof process & { loadEnvFile?: (path?: string) => void }).loadEnvFile
try {
	loadEnvFile?.('.env')
}
catch {
	// 没有 .env 时继续，使用手动数据即可
}

const adapters = [
	{
		name: 'Bangumi',
		enabled: Boolean(process.env.HOBBY_BANGUMI_USER?.trim()),
		run: collectBangumi,
	},
	{
		name: 'Steam',
		enabled: Boolean(process.env.HOBBY_STEAM_KEY?.trim() && process.env.HOBBY_STEAM_ID?.trim()),
		run: collectSteam,
	},
]

const activeAdapters = adapters.filter(adapter => adapter.enabled)
if (!activeAdapters.length) {
	console.log('没有配置任何兴趣同步源。')
	console.log('手动维护 content/data/hobbies.ts 即可；需要自动同步时，在 .env 里配置：')
	console.log('  HOBBY_BANGUMI_USER=你的 Bangumi 用户名')
	console.log('  HOBBY_BANGUMI_TOKEN=可选，私有收藏需要')
	console.log('  HOBBY_STEAM_KEY=Steam Web API Key')
	console.log('  HOBBY_STEAM_ID=SteamID64 或自定义 URL 名')
	process.exit(0)
}

const generated: HobbyItemMap = {}
const summary: { name: string, count: number }[] = []

try {
	for (const adapter of activeAdapters) {
		console.log(`→ 正在同步 ${adapter.name}…`)
		const result = await adapter.run()
		generated[result.key] = [...(generated[result.key] ?? []), ...result.items]
		summary.push({ name: adapter.name, count: result.items.length })
		console.log(`  ${result.items.length} 条`)
	}
}
catch (error) {
	console.error(`✖ ${error instanceof Error ? error.message : String(error)}`)
	console.error('同步失败，已保留原有 generated 文件，未写入。')
	process.exit(1)
}

if (dryRun) {
	console.log(`dry-run：${summary.map(item => `${item.name} ${item.count} 条`).join('，')}，未写入文件。`)
	process.exit(0)
}

const header = `// 此文件由 \`pnpm sync:hobbies\` 生成，请勿手动编辑。
// Generated by \`pnpm sync:hobbies\`. Do not edit manually.
import type { HobbyItemMap } from '../../shared/types/hobby'

`
const body = `const generated: HobbyItemMap = ${JSON.stringify(generated, null, '\t')}

export default generated
`

fs.writeFileSync(outputPath, header + body, 'utf8')
console.log(`✔ 已写入 ${path.relative(process.cwd(), outputPath)}`)
console.log(summary.map(item => `${item.name}：${item.count} 条`).join('，'))
